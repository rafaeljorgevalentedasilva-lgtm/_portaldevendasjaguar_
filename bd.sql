-- 9) Estatísticas por loja para exibição no painel administrativo.
-- A função só retorna dados quando chamada por um administrador autorizado.
create or replace function public.estatisticas_lojas()
returns table (
  loja_id bigint,
  acessos bigint,
  conversas bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    l.id as loja_id,
    count(e.id) filter (where e.tipo = 'visita')::bigint as acessos,
    count(e.id) filter (where e.tipo = 'conversa')::bigint as conversas
  from public."Lojas" l
  left join public.loja_eventos e on e.loja_id = l.id
  where public.eh_admin()
  group by l.id;
$$;

revoke all on function public.estatisticas_lojas() from public;
grant execute on function public.estatisticas_lojas() to authenticated;


-- 10) Estatísticas agregadas públicas para exibição no detalhamento da loja.
-- A função retorna somente totais; não expõe eventos individuais nem identificadores.
create or replace function public.estatisticas_publicas_lojas(p_loja_id bigint)
returns table (
  acessos bigint,
  conversas bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    count(e.id) filter (where e.tipo = 'visita')::bigint as acessos,
    count(e.id) filter (where e.tipo = 'conversa')::bigint as conversas
  from public."Lojas" l
  left join public.loja_eventos e on e.loja_id = l.id
  where l.id = p_loja_id
    and l.ativo = true;
$$;

revoke all on function public.estatisticas_publicas_lojas(bigint) from public;
grant execute on function public.estatisticas_publicas_lojas(bigint) to anon, authenticated;

-- 11) Avaliações públicas das lojas (sem exigir login).
-- Um identificador aleatório persistido no navegador limita a uma avaliação
-- por loja e navegador. A restrição UNIQUE no banco impede duplicidade mesmo
-- em envios simultâneos.
create table if not exists public.loja_avaliacoes (
  id bigint generated by default as identity primary key,
  loja_id bigint not null references public."Lojas"(id) on delete cascade,
  visitante_hash text not null,
  nota smallint not null check (nota between 0 and 5),
  created_at timestamptz not null default now(),
  constraint loja_avaliacoes_loja_visitante_unique unique (loja_id, visitante_hash)
);

create index if not exists loja_avaliacoes_loja_idx
  on public.loja_avaliacoes (loja_id);

alter table public.loja_avaliacoes enable row level security;
revoke all on public.loja_avaliacoes from public, anon, authenticated;

-- A gravação ocorre exclusivamente pela função; a chave única garante
-- que o mesmo navegador não consiga avaliar duas vezes a mesma loja.
create or replace function public.avaliar_loja(
  p_loja_id bigint,
  p_nota smallint,
  p_visitante_hash text
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  inseridas integer;
begin
  if p_nota is null or p_nota < 0 or p_nota > 5 then
    raise exception 'Nota inválida. Use uma nota de 0 a 5.';
  end if;

  if p_visitante_hash is null or length(p_visitante_hash) <> 64
     or p_visitante_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'Identificador de visitante inválido.';
  end if;

  if not exists (
    select 1 from public."Lojas" l
    where l.id = p_loja_id and l.ativo = true
  ) then
    raise exception 'Loja indisponível.';
  end if;

  insert into public.loja_avaliacoes (loja_id, visitante_hash, nota)
  values (p_loja_id, p_visitante_hash, p_nota)
  on conflict (loja_id, visitante_hash) do nothing;

  get diagnostics inseridas = row_count;
  return inseridas = 1;
end;
$$;

revoke all on function public.avaliar_loja(bigint, smallint, text) from public;
grant execute on function public.avaliar_loja(bigint, smallint, text) to anon, authenticated;

-- Retorna somente média e quantidade; nunca expõe os identificadores.
create or replace function public.avaliacoes_publicas_lojas()
returns table (
  loja_id bigint,
  media numeric,
  total bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    l.id as loja_id,
    coalesce(round(avg(a.nota)::numeric, 1), 0::numeric) as media,
    count(a.id)::bigint as total
  from public."Lojas" l
  left join public.loja_avaliacoes a on a.loja_id = l.id
  where l.ativo = true
  group by l.id;
$$;

revoke all on function public.avaliacoes_publicas_lojas() from public;
grant execute on function public.avaliacoes_publicas_lojas() to anon, authenticated;

